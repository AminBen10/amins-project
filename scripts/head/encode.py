"""Step 5: pack the cage and its attributes into src/three/headAsset.js.

Binary layout (little-endian), deflated (raw deflate) and base64'd into HEAD_CAGE:
  'HD01' | u16 nv | u16 nq | f32 bmin[3] | f32 bmax[3]
  u16 nPhi | u16 nY | f32 y0 | f32 dy | f32 rScale | u16 nAttr | u16 0
  positions  nv x 3 quantized to 12 bits over [bmin, bmax]; per axis zigzag deltas in
             vertex order, written as a low-byte plane then a high-byte plane (3 axes)
  quads      u32 byte length, then zigzag varint deltas of the flattened index list
  attributes nAttr planes of nv bytes: ao, cavity, thickness, edgeH, edgeB, part
  grid       nY x nPhi radii (u16, r * rScale), zigzag deltas along phi, low plane, high plane
Edges are stored as 128 + sign(d) * sqrt(min(|d|, 0.5) / 0.5) * 127 (fine near the edge)."""
import base64
import json
import struct
import zlib

import numpy as np

QBITS = 12
EDGE_MAX = 0.5
THICK_MAX = 0.3
R_SCALE = 20000.0
ATTRS = ('ao', 'cavity', 'thickness', 'edgeH', 'edgeB', 'part')


def zigzag(a):
    a = np.asarray(a, np.int64)
    return np.where(a >= 0, 2 * a, -2 * a - 1)


def planes16(v):
    v = np.asarray(v, np.int64)
    assert v.min() >= 0 and v.max() < 65536
    return (v & 255).astype(np.uint8).tobytes() + (v >> 8).astype(np.uint8).tobytes()


def varint(values):
    out = bytearray()
    for c in values:
        c = int(c)
        while c >= 128:
            out.append((c & 127) | 128)
            c >>= 7
        out.append(c)
    return bytes(out)


def edge_code(d):
    d = np.clip(d, -EDGE_MAX, EDGE_MAX)
    return np.round(128 + np.sign(d) * np.sqrt(np.abs(d) / EDGE_MAX) * 127).astype(np.uint8)


def encode_asset(path, P, Q, attrs, grid, meta):
    nv, nq = len(P), len(Q)
    assert nv < 65536 and nq < 65536
    bmin = P.min(0) - 1e-4
    bmax = P.max(0) + 1e-4
    qmax = (1 << QBITS) - 1
    q = np.round((P - bmin) / (bmax - bmin) * qmax).astype(np.int64)
    phis, ys, r = grid
    out = bytearray(b'HD01')
    out += struct.pack('<HH3f3f', nv, nq, *bmin, *bmax)
    out += struct.pack('<HHfffHH', len(phis), len(ys), float(ys[0]), float(ys[1] - ys[0]), R_SCALE, len(ATTRS), 0)
    for axis in range(3):
        out += planes16(zigzag(np.diff(q[:, axis], prepend=0)))
    qs = varint(zigzag(np.diff(Q.reshape(-1), prepend=0)))
    out += struct.pack('<I', len(qs)) + qs
    planes = {
        'ao': np.round(np.clip(attrs['ao'], 0, 1) * 255),
        'cavity': np.round(np.clip(attrs['cavity'], 0, 1) * 255),
        'thickness': np.round(np.clip(attrs['thickness'] / THICK_MAX, 0, 1) * 255),
        'edgeH': edge_code(attrs['edgeH']),
        'edgeB': edge_code(attrs['edgeB']),
        'part': attrs['part'],
    }
    for name in ATTRS:
        out += np.asarray(planes[name], np.uint8).tobytes()
    rq = np.round(r * R_SCALE).astype(np.int64)
    out += planes16(zigzag(np.diff(rq, axis=1, prepend=0)).reshape(-1))
    comp = zlib.compressobj(9, zlib.DEFLATED, -15, 9)
    packed = comp.compress(bytes(out)) + comp.flush()
    b64 = base64.b64encode(packed).decode('ascii')
    meta = dict(meta, encoding={'qbits': QBITS, 'edgeMax': EDGE_MAX, 'thickMax': THICK_MAX, 'attrs': list(ATTRS)})
    with open(path, 'w') as fh:
        fh.write('// Generated by scripts/head/build_head.py. Do not edit by hand.\n')
        fh.write('// Practice head: MakeHuman base mesh and targets, CC0 1.0 (makehumancommunity/makehuman,\n')
        fh.write('// LICENSE.md section C). Neutral adult man, nobody in particular. Layout: scripts/head/README.md.\n')
        fh.write('export const HEAD_META = ' + json.dumps(meta, separators=(',', ':')) + ';\n')
        fh.write("export const HEAD_CAGE = '" + b64 + "';\n")
    return len(packed)
